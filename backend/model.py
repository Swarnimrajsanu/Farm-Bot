def _find_solution(class_name: str) -> str:
    """Find the best matching treatment solution for a disease class name."""
    normalized = class_name.lower().replace("___", "_").replace(" ", "_")
    
    # Try direct key matches
    for key, solution in SOLUTIONS.items():
        if key in normalized:
            return solution
    
    # Check if healthy
    if "healthy" in normalized:
        return "Plant is healthy! Continue regular care and monitoring."
    
    return "Consult a local agricultural expert for specific treatment advice."


def _format_disease_name(class_name: str) -> str:
    """Convert dataset folder name to human-readable disease name."""
    # Split plant and disease
    if "___" in class_name:
        parts = class_name.split("___", 1)
        plant = parts[0].replace("_", " ").replace(",", ",")
        # Clean up plant name
        plant = plant.replace("(including sour)", "").strip()
        plant = plant.replace("(maize)", "").strip()
        
        disease = parts[1].replace("_", " ").strip()
        # Clean up disease name
        disease = disease.replace("  ", " ")
        
        return f"{plant} - {disease}"
    
    return class_name.replace("_", " ")


class PlantDiseaseModel:
    """
    Plant disease classifier using Transfer Learning (MobileNetV2 or ResNet18).
    
    Automatically detects the model architecture from class_mapping.json.
    If a trained model file exists at 'plant_disease_model.pth', it loads those weights.
    If 'class_mapping.json' exists (from train.py), it uses the exact class order.
    Otherwise, it uses pretrained ImageNet weights for demo purposes.
    """

    def __init__(self, model_path: str = "plant_disease_model.pth",
                 class_map_path: str = "class_mapping.json"):
        self.device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
        self.model_path = model_path
        self.class_map_path = class_map_path

        # Load class mapping & detect model type
        self.disease_classes, self.model_type = self._load_classes(class_map_path)
        self.num_classes = len(self.disease_classes)

        # Image preprocessing (matches ImageNet / PlantVillage training)
        self.transform = transforms.Compose([
            transforms.Resize((256, 256)),
            transforms.CenterCrop(224),
            transforms.ToTensor(),
            transforms.Normalize(
                mean=[0.485, 0.456, 0.406],
                std=[0.229, 0.224, 0.225],
            ),
        ])

        # Build model
        self.model = self._build_model()
        self.model.to(self.device)
        self.model.eval()

        print(f"[MODEL] Architecture: {self.model_type.upper()}")
        print(f"[MODEL] Device: {self.device}")
        print(f"[MODEL] Classes: {self.num_classes}")

    def _load_classes(self, class_map_path: str):
        """Load class names and model type from class_mapping.json or use defaults."""
        model_type = "mobilenet"  # default
        if Path(class_map_path).exists():
            print(f"[MODEL] Loading class mapping from: {class_map_path}")
            with open(class_map_path) as f:
                mapping = json.load(f)
            idx_to_class = mapping.get("idx_to_class", {})
            model_type = mapping.get("model_type", "mobilenet")
            # Sort by index to get ordered list
            classes = [idx_to_class[str(i)] for i in range(len(idx_to_class))]
            print(f"[MODEL] Loaded {len(classes)} classes (model_type={model_type})")
            return classes, model_type
        else:
            print("[MODEL] No class_mapping.json found, using defaults")
            return DEFAULT_DISEASE_CLASSES, model_type

    def _build_model(self):
        """Build model matching the architecture used during training."""
        if self.model_type == "mobilenet":
            return self._build_mobilenet()
        else:
            return self._build_resnet()

    def _build_mobilenet(self):
        """Build MobileNetV2 with custom classifier head."""
        model = models.mobilenet_v2(weights=models.MobileNet_V2_Weights.DEFAULT)
        model.classifier = nn.Sequential(
            nn.Dropout(0.2),
            nn.Linear(model.last_channel, self.num_classes),
        )

        if Path(self.model_path).exists():
            print(f"[MODEL] ✓ Loading trained MobileNetV2 weights: {self.model_path}")
            state_dict = torch.load(self.model_path, map_location=self.device)
            model.load_state_dict(state_dict)
            self._trained = True
        else:
            print("[MODEL] No trained weights — using pretrained MobileNetV2 (demo mode)")
            self._trained = False

        return model

    def _build_resnet(self):
        """Build ResNet18 with custom classifier head."""
        model = models.resnet18(weights=models.ResNet18_Weights.DEFAULT)
        num_features = model.fc.in_features
        model.fc = nn.Sequential(
            nn.Dropout(0.3),
            nn.Linear(num_features, self.num_classes),
        )

        if Path(self.model_path).exists():
            print(f"[MODEL] ✓ Loading trained ResNet18 weights: {self.model_path}")
            state_dict = torch.load(self.model_path, map_location=self.device)
            model.load_state_dict(state_dict)
            self._trained = True
        else:
            print("[MODEL] No trained weights — using pretrained ResNet18 (demo mode)")
            self._trained = False

        return model

    def predict(self, image_path: str) -> dict:
        """
        Predict plant disease from an image.

        Args:
            image_path: Path to the plant image file.

        Returns:
            dict with 'disease', 'confidence', and 'solution'.
        """
        # Load and preprocess image
        image = Image.open(image_path).convert("RGB")
        input_tensor = self.transform(image).unsqueeze(0).to(self.device)

        # Inference
        with torch.no_grad():
            outputs = self.model(input_tensor)
            probabilities = torch.nn.functional.softmax(outputs, dim=1)
            confidence, predicted_idx = torch.max(probabilities, 1)

        class_name = self.disease_classes[predicted_idx.item()]
        conf_value = confidence.item()

        # Format disease name for display
        display_name = _format_disease_name(class_name)

        # Get treatment solution
        solution = _find_solution(class_name)

        return {
            "disease": display_name,
            "class_id": class_name,
            "confidence": round(conf_value, 4),
            "solution": solution,
            "is_healthy": "healthy" in class_name.lower(),
        }


